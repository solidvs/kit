import { dirname, relative, resolve } from 'node:path';

/**
 * One Prisma model for every supported engine (ADR-0016). A system writes `prisma/schema.prisma`
 * for the reference engine (PostgreSQL) using only what both engines support; the SQL Server
 * schema is derived from it with a fixed translation of native types. Anything outside the rules
 * is refused, naming the line, so the two engines can never drift apart silently.
 */

export class NeutralSchemaError extends Error {
  readonly problems: string[];

  constructor(problems: string[]) {
    super(`The Prisma schema is not engine-neutral (ADR-0016):\n- ${problems.join('\n- ')}`);
    this.name = 'NeutralSchemaError';
    this.problems = problems;
  }
}

const SCALARS = new Set(['String', 'Boolean', 'Int', 'BigInt', 'Float', 'Decimal', 'DateTime', 'Json', 'Bytes']);

/** Longest `@db.VarChar(n)` that SQL Server stores as `NVARCHAR(n)`; beyond it, use `@db.Text`. */
const MAX_VARCHAR = 4000;

type Translation = (args: string | undefined) => string;

/** PostgreSQL native type → SQL Server native type. A type missing here is refused. */
const NATIVE_TYPES: Record<string, Translation> = {
  Text: () => 'NVarChar(Max)',
  VarChar: (args) => `NVarChar(${args})`,
  Char: (args) => `NChar(${args})`,
  Uuid: () => 'UniqueIdentifier',
  SmallInt: () => 'SmallInt',
  Integer: () => 'Int',
  BigInt: () => 'BigInt',
  Decimal: (args) => `Decimal(${args})`,
  Real: () => 'Real',
  DoublePrecision: () => 'Float',
  Boolean: () => 'Bit',
  Date: () => 'Date',
  Timestamp: () => 'DateTime2',
  Timestamptz: () => 'DateTimeOffset',
};

const STRING_STORAGE = new Set(['Text', 'VarChar', 'Char', 'Uuid']);

type Block = { kind: string; name: string };

/** Checks the rules and returns the problems found (empty when the schema is neutral). */
export function neutralSchemaProblems(source: string): string[] {
  return walk(source).problems;
}

/**
 * Derives the SQL Server schema from the reference schema. `sourcePath` and `targetPath` let the
 * generator's relative `output` keep pointing at the same folder.
 */
export function deriveSqlServerSchema(source: string, paths: { sourcePath: string; targetPath: string }): string {
  const { problems, lines } = walk(source, paths);
  if (problems.length > 0) throw new NeutralSchemaError(problems);
  return [
    `// Generated by \`solidvs-data derive\` from ${relative(dirname(paths.targetPath), paths.sourcePath)}. Do not edit:`,
    '// change the reference schema and run the command again (ADR-0016).',
    '',
    ...lines,
  ].join('\n');
}

function walk(source: string, paths?: { sourcePath: string; targetPath: string }): { problems: string[]; lines: string[] } {
  const problems: string[] = [];
  const lines: string[] = [];
  let block: Block | undefined;
  let provider: string | undefined;

  source.split('\n').forEach((original, index) => {
    const at = `line ${index + 1}`;
    let line = original;
    const code = original.replace(/\/\/.*$/, '').trim();

    if (!block) {
      const open = /^(\w+)\s+(\w+)\s*\{$/.exec(code);
      if (open) {
        block = { kind: open[1]!, name: open[2]! };
        if (!['model', 'generator', 'datasource'].includes(block.kind)) {
          problems.push(`${at}: \`${block.kind} ${block.name}\` is not supported on every engine; use a model with a text column validated by the application`);
        }
      }
      lines.push(line);
      return;
    }

    if (code === '}') {
      block = undefined;
      lines.push(line);
      return;
    }

    if (block.kind === 'datasource') {
      const providerLine = /^provider\s*=\s*"(\w+)"$/.exec(code);
      if (providerLine) {
        provider = providerLine[1];
        if (provider !== 'postgresql') problems.push(`${at}: the reference schema declares provider "postgresql"`);
        line = original.replace(/"\w+"/, '"sqlserver"');
      } else if (/^url\s*=/.test(code)) {
        problems.push(`${at}: the connection belongs in prisma.config.ts, built from the configuration file`);
      }
    } else if (block.kind === 'generator' && paths) {
      const output = /^output\s*=\s*"([^"]+)"$/.exec(code);
      if (output) {
        const target = resolve(dirname(paths.sourcePath), output[1]!);
        line = original.replace(`"${output[1]}"`, `"${relative(dirname(paths.targetPath), target)}"`);
      }
    } else if (block.kind === 'model' && code && !code.startsWith('@@')) {
      line = field(original, code, at, problems);
    }
    lines.push(line);
  });

  if (provider === undefined) problems.push('the schema has no datasource with a provider');
  return { problems, lines };
}

function field(original: string, code: string, at: string, problems: string[]): string {
  const match = /^(\w+)\s+(\w+)(\[\])?(\?)?\s*(.*)$/.exec(code);
  if (!match) return original;
  const [, name, type, list, , attributes = ''] = match;
  if (!SCALARS.has(type!)) return original; // a relation

  if (type === 'Json') problems.push(`${at}: \`${name}\` is Json, which SQL Server does not support; store text (@db.Text) and validate it with zod`);
  if (list) problems.push(`${at}: \`${name}\` is a list of ${type}; use a related model`);
  if (attributes.includes('dbgenerated(')) problems.push(`${at}: \`${name}\` uses dbgenerated(), which is engine-specific SQL`);

  const natives = [...attributes.matchAll(/@db\.(\w+)(?:\(([^)]*)\))?/g)];
  if (type === 'String') {
    const storage = natives.find(([, native]) => STRING_STORAGE.has(native!));
    if (!storage) {
      problems.push(`${at}: \`${name}\` must declare its storage, @db.Text or @db.VarChar(n), so both engines accept the same lengths`);
    } else if (storage[1] === 'Text' && /@(id|unique)\b/.test(attributes)) {
      problems.push(`${at}: \`${name}\` is a key; keys use @db.VarChar(n) or @db.Uuid, not @db.Text`);
    } else if (storage[1] === 'VarChar' && Number(storage[2]) > MAX_VARCHAR) {
      problems.push(`${at}: \`${name}\` is longer than ${MAX_VARCHAR}; use @db.Text`);
    }
  }

  let line = original;
  for (const [whole, native, args] of natives) {
    const translate = NATIVE_TYPES[native!];
    if (!translate) {
      problems.push(`${at}: @db.${native} has no SQL Server translation; use a type from the platform kit's table or extend it with tests`);
      continue;
    }
    line = line.replace(whole, `@db.${translate(args)}`);
  }
  return line;
}
