import { describe, expect, it } from 'vitest';

import { AUDIT_EVENT_MODEL } from './audit-trail.js';
import { deriveSqlServerSchema, NeutralSchemaError, neutralSchemaProblems } from './neutral-schema.js';

const header = `generator client {
  provider = "prisma-client"
  output   = "../src/generated/prisma"
}

datasource db {
  provider = "postgresql"
}
`;

const paths = { sourcePath: '/s/prisma/schema.prisma', targetPath: '/s/prisma/sqlserver/schema.prisma' };

describe('engine-neutral Prisma schema (ADR-0016)', () => {
  it('derives SQL Server types and keeps the generator output in the same folder', () => {
    const derived = deriveSqlServerSchema(
      `${header}
model Order {
  id        String   @id @db.VarChar(36)
  code      String   @unique @db.Char(8)
  note      String?  @db.Text
  ref       String   @db.Uuid
  total     Decimal  @db.Decimal(12, 2)
  placedAt  DateTime @db.Timestamptz(3)
  items     Item[]
}
`,
      paths,
    );
    expect(derived).toContain('provider = "sqlserver"');
    expect(derived).toContain('output   = "../../src/generated/prisma"');
    expect(derived).toContain('@db.NVarChar(36)');
    expect(derived).toContain('@db.NChar(8)');
    expect(derived).toContain('@db.NVarChar(Max)');
    expect(derived).toContain('@db.UniqueIdentifier');
    expect(derived).toContain('@db.Decimal(12, 2)');
    expect(derived).toContain('@db.DateTimeOffset');
    expect(derived).toContain('items     Item[]');
    expect(derived.startsWith('// Generated by `solidvs-data derive` from ../schema.prisma.')).toBe(true);
  });

  it('accepts the platform audit model as it is', () => {
    expect(neutralSchemaProblems(`${header}\n${AUDIT_EVENT_MODEL}\n`)).toEqual([]);
    expect(deriveSqlServerSchema(`${header}\n${AUDIT_EVENT_MODEL}\n`, paths)).toContain('@db.NVarChar(200)');
  });

  it.each([
    ['enum Status {\n  open\n}', 'enum Status'],
    ['model A {\n  id Int @id\n  data Json\n}', 'Json'],
    ['model A {\n  id Int @id\n  tags String[] @db.Text\n}', 'list of String'],
    ['model A {\n  id Int @id\n  name String\n}', 'must declare its storage'],
    ['model A {\n  id String @id @db.Text\n}', 'is a key'],
    ['model A {\n  id Int @id\n  name String @db.VarChar(5000)\n}', 'longer than 4000'],
    ['model A {\n  id Int @id\n  at DateTime @db.Time\n}', '@db.Time has no SQL Server translation'],
    ['model A {\n  id Int @id @default(dbgenerated("1"))\n}', 'dbgenerated'],
  ])('refuses %j', (model, message) => {
    const problems = neutralSchemaProblems(`${header}\n${model}\n`);
    expect(problems.join('\n')).toContain(message);
    expect(() => deriveSqlServerSchema(`${header}\n${model}\n`, paths)).toThrow(NeutralSchemaError);
  });

  it('refuses a reference schema for another engine or with a connection', () => {
    expect(neutralSchemaProblems(header.replace('postgresql', 'sqlserver')).join()).toContain('provider "postgresql"');
    expect(neutralSchemaProblems(header.replace('provider = "postgresql"', 'provider = "postgresql"\n  url = env("X")')).join()).toContain('prisma.config.ts');
  });

  it('names the line of each problem', () => {
    expect(neutralSchemaProblems(`${header}\nmodel A {\n  id Int @id\n  data Json\n}\n`)[0]).toMatch(/^line 12:/);
  });
});
